def extract_and_add_mcqs(dir_path, sol_dir, ch_list, grade_num, max_per_ch=12):
    keys = ['ក', 'ខ', 'គ', 'ឃ']
    for ch_num, ch_title, cat in ch_list:
        tex_file = os.path.join(dir_path, f"chapter {ch_num}.tex")
        sol_file = os.path.join(sol_dir, f"chapter_{ch_num:02d}_sol.tex")
        
        if not os.path.exists(tex_file):
            continue

        with open(tex_file, 'r', encoding='utf-8', errors='ignore') as f:
            content = f.read()

        answers = []
        if os.path.exists(sol_file):
            with open(sol_file, 'r', encoding='utf-8', errors='ignore') as sf:
                sol_content = sf.read()
                answers = re.findall(r'\\ansbadge\{([^}]+)\}', sol_content)

        pattern = r'\\item\s+(.*?)\s*\\begin\{(?:ktasks|tasks)\}(?:\[.*?\])?(?:\(\d+\))?\s*(.*?)\\end\{(?:ktasks|tasks)\}'
        matches = re.findall(pattern, content, re.DOTALL)

        added = 0
        for idx, (q_raw, tasks_raw) in enumerate(matches):
            if added >= max_per_ch:
                break
            
            q_text = re.sub(r'%.*$', '', q_raw, flags=re.MULTILINE)
            q_text = re.sub(r'\s+', ' ', q_text).strip()
            
            if len(q_text) < 5 or 'ពហុជ្រើសរើស' in q_text[:25] or 'Multiple Choice' in q_text:
                continue

            raw_opts = [re.sub(r'\s+', ' ', re.sub(r'%.*$', '', t, flags=re.MULTILINE)).strip() for t in re.split(r'\\task\s+', tasks_raw) if t.strip()]
            if len(raw_opts) != 4:
                continue

            options = [{"key": keys[i], "text": raw_opts[i]} for i in range(4)]
            ans = answers[idx] if idx < len(answers) else keys[idx % 4]
            
            diff = "ងាយ" if idx < 5 else ("មធ្យម" if idx < 10 else "លំបាក")
            pts = 1 if diff == "ងាយ" else (2 if diff == "មធ្យម" else 3)

            q_id = f"q_g{grade_num}_c{ch_num:02d}_{idx+1:03d}"
            # Check not already present
            if any(q["id"] == q_id for q in all_qbank):
                continue

            all_qbank.append({
                "id": q_id,
                "grade": grade_num,
                "chapter": f"មេរៀនទី {ch_num} {ch_title}" if grade_num != 10 else f"ជំពូកទី {ch_num} {ch_title}",
                "category": cat,
                "type": "mcq",
                "difficulty": diff,
                "points": pts,
                "question": q_text,
                "options": options,
                "answer": ans,
                "explanation": f"ចម្លើយត្រឹមត្រូវគឺជម្រើស ({ans}) ស្របតាមក្បួនដោះស្រាយ និងទ្រឹស្តីបទនៃ {ch_title}។"
            })
            added += 1

